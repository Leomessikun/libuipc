"""Follow the real free cuff and closed mesh sections toward the armhole.

The legacy six-point ``shoulder_polygon`` is an armhole seam, not a free
cuff. The older autogenerated rings extend from that seam into the torso.
Here every interior section is a connected triangle/plane intersection;
its barycentric locations stay on the cloth as it deforms. No polar sorting
of disconnected garment points is used to invent a closed loop.
"""
from __future__ import annotations

